-- Campus Continuity schema (Flyway V1). Tables are created exactly as documented in docs/03-database-schema.md.
CREATE TABLE laboratory (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           VARCHAR(80)  NOT NULL UNIQUE,
  name           VARCHAR(160) NOT NULL,
  building       VARCHAR(160),
  capacity       INTEGER      NOT NULL CHECK (capacity >= 0),
  max_team_size  INTEGER      NOT NULL CHECK (max_team_size >= 1),
  equipment      VARCHAR(1000) NOT NULL DEFAULT '',
  status         VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','DISRUPTED','DEACTIVATED')),
  reason         VARCHAR(500)
);
CREATE TABLE time_slot (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(80)  NOT NULL UNIQUE,
  label            VARCHAR(160) NOT NULL,
  day_of_week      VARCHAR(20),
  start_time       VARCHAR(10),
  duration_minutes INTEGER      NOT NULL CHECK (duration_minutes > 0),
  status           VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','DISRUPTED','DEACTIVATED')),
  reason           VARCHAR(500)
);
CREATE TABLE team (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id       VARCHAR(80)  NOT NULL UNIQUE,   -- authoritative request store used to verify Bloom positives
  code             VARCHAR(80)  NOT NULL UNIQUE,
  name             VARCHAR(160) NOT NULL,
  size             INTEGER      NOT NULL CHECK (size >= 1),
  requirements     VARCHAR(1000) NOT NULL DEFAULT '',
  duration_minutes INTEGER      NOT NULL CHECK (duration_minutes > 0),
  eligible_slots   VARCHAR(1000) NOT NULL DEFAULT '',
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE TABLE request_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id    VARCHAR(80) NOT NULL,
  team_code     VARCHAR(80),
  bloom_result  VARCHAR(20) NOT NULL,   -- NEGATIVE | POSSIBLE
  exact_result  VARCHAR(20) NOT NULL,   -- NOT_CHECKED | ABSENT | PRESENT
  outcome       VARCHAR(30) NOT NULL,   -- ACCEPTED | REJECTED_DUPLICATE | REJECTED_INVALID
  source        VARCHAR(20) NOT NULL,   -- MANUAL | CSV | SEED | SIMULATION
  message       VARCHAR(500),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_request_log_created ON request_log (id DESC);
CREATE TABLE run_record (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       VARCHAR(20) NOT NULL,      -- ALLOCATION | SIMULATION | BENCHMARK
  name       VARCHAR(200) NOT NULL,
  summary    VARCHAR(1000) NOT NULL,
  payload    TEXT NOT NULL,             -- JSON of the full result (trace omitted)
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_run_kind ON run_record (kind, id DESC);
CREATE TABLE activity_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     VARCHAR(60)  NOT NULL,
  detail     VARCHAR(1000) NOT NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
